    "This report is generated by an AI-based stroke-risk classification system "
    "and is intended for informational and educational purposes only. It is not "
    "a medical diagnosis and should not replace professional medical advice, "
    "diagnosis, or treatment. Consult a qualified healthcare professional for "
    "medical concerns."
